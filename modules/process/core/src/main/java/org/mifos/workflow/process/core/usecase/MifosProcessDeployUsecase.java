package org.mifos.workflow.process.core.usecase;

import java.io.Serial;
import java.util.UUID;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.experimental.FieldNameConstants;
import org.mifos.commons.boot.operation.core.usecase.MifosUsecase;

/// Deploys a workflow process definition.
public interface MifosProcessDeployUsecase
        extends MifosUsecase<MifosProcessDeployUsecase.Request, MifosProcessDeployUsecase.Response> {
    /// Request containing the process definition to deploy.
    @Builder
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @FieldNameConstants
    class Request implements MifosRequest {
        @Serial
        private static final long serialVersionUID = 1L;

        private String name;
        private String processDefinition;
    }

    /// Response containing the result of the deployment.
    @Builder
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @FieldNameConstants
    class Response implements MifosResponse {
        @Serial
        private static final long serialVersionUID = 1L;

        private UUID id;
    }
}
